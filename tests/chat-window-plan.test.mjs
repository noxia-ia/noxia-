import assert from "node:assert/strict";
import { windowTierForPlan } from "../src/lib/chat-window-plan.ts";
const exp = { free: "free", plus: "plus", pro: "pro", ultra: "ultra", daily: "plus", weekly: "plus", monthly: "pro", annual: "ultra" };
for (const [k, v] of Object.entries(exp)) assert.equal(windowTierForPlan(k), v, k);
for (const bad of ["__proto__", "constructor", "toString", "inconnu"]) assert.equal(windowTierForPlan(bad), "plus", bad);
for (const none of [null, undefined]) assert.equal(windowTierForPlan(none), "free");
console.log("  ✔ formules → paliers, formule inconnue → Plus, jamais Free pour un payant");
import { resolveWindowTier, GRACE_MS } from "../src/lib/chat-window-plan.ts";
const now = Date.parse("2026-10-12T12:00:00Z"), iso = ms => new Date(now + ms).toISOString();
const sub = (plan, ms, status = "active") => ({ status, plan, expires_at: ms === null ? null : iso(ms) });
assert.equal(resolveWindowTier(null, now), "free");
assert.equal(resolveWindowTier(sub("pro", 3600e3), now), "pro", "en cours");
assert.equal(resolveWindowTier(sub("pro", -3600e3), now), "pro", "expiré depuis 1 h : grâce");
assert.equal(resolveWindowTier(sub("annual", -GRACE_MS), now), "ultra", "exactement 24 h : encore la grâce");
assert.equal(resolveWindowTier(sub("pro", -GRACE_MS - 1000), now), "free", "au-delà de 24 h : Free");
for (const st of ["expired", "cancelled", "suspended", "pending"]) assert.equal(resolveWindowTier(sub("pro", -3600e3, st), now), "free", st);
assert.equal(resolveWindowTier({ status: "active", plan: "pro", expires_at: "n'importe quoi" }, now), "free");
assert.equal(resolveWindowTier(sub("free", null), now), "free");
console.log("  ✔ grâce de 24 h après l'échéance, puis Free ; pas de grâce si suspendu/annulé/expiré par l'admin");
