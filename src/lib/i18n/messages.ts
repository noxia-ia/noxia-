const DICTIONARIES: Partial<Record<LocaleCode, Record<MessageKey, string>>> = { fr, en };
/** Retourne la fonction de traduction ; langue absente → français. Une clé manquante retombe sur le français. */
export function getT(locale: LocaleCode) {
  const dict = DICTIONARIES[locale] ?? fr;
  return (key: MessageKey): string => dict[key] ?? fr[key];
}
export type T = ReturnType<typeof getT>;
/** Dictionnaire complet pour un composant client (les fonctions ne traversent pas la frontière serveur/client). */
export function getMessages(locale: LocaleCode): Record<MessageKey, string> {
  const t = getT(locale);
  return Object.fromEntries((Object.keys(fr) as MessageKey[]).map(k => [k, t(k)])) as Record<MessageKey, string>;
}
